"""Which HIPAA Safe Harbor identifier categories this tool looks for, and how well that is known.

    python -m deid.audit.coverage            # prints docs/COVERAGE.md
    python -m deid.audit.coverage --check    # fails if docs/COVERAGE.md is out of date

The 18 categories follow 45 CFR 164.514(b)(2)(i) as summarized in secondary sources; check the
regulation itself before relying on this table. It is a statement about what the tool tries to find,
not a statement that notes it has cleaned meet Safe Harbor: that also needs a person to review the
output and the "no actual knowledge" condition to hold.

Status values:
  measured     a type the detector is scored on, on the project's synthetic sets (numbers in docs/EVIDENCE.md)
  rule         found by a rule with no model; tested on invented text, not scored on labeled notes
  asked        the model is asked for it in its prompt, but no result is reported for this category on its own
  partial      only some of the category is handled
  not covered  not looked for; a person must handle it
"""

import argparse
import sys
from html import escape
from pathlib import Path

STATUSES = ("measured", "rule", "asked", "partial", "not covered")

CATEGORIES = [
    (1, "Names", "measured", "NAME (patients, relatives, clinicians); scored on 2,587 labeled names in the 400 held-out notes."),
    (2, "Geographic subdivisions smaller than a state", "partial",
     "ADDRESS (street addresses, towns) is measured; ZIP codes after a state or the word ZIP are cut to three digits by a rule. County, precinct and facility names are not specifically tested."),
    (3, "Dates (except year) tied to a person, and ages over 89", "partial",
     "DATE is measured. By default dates are shifted, which keeps intervals but is not the Safe Harbor form; `date_mode=\"year\"` keeps only the year. Ages of 90 or more become \"90+\" by a rule (tested on invented text)."),
    (4, "Telephone numbers", "measured", "PHONE."),
    (5, "Fax numbers", "asked", "PHONE (the prompt names fax numbers); 150 fax numbers are labeled in the 600-note set and scored together with the other phone numbers."),
    (6, "Email addresses", "measured", "EMAIL."),
    (7, "Social security numbers", "asked", "ID; 28 social security numbers are labeled in the 600-note set and scored together with the other IDs."),
    (8, "Medical record numbers", "asked", "ID; scored together with the other IDs (600 MRNs labeled in the 600-note set)."),
    (9, "Health plan beneficiary numbers", "asked", "ID (insurance numbers); scored together with the other IDs."),
    (10, "Account numbers", "asked", "ID; scored together with the other IDs."),
    (11, "Certificate and license numbers", "not covered", "Not in the prompt and not tested."),
    (12, "Vehicle identifiers and license plates", "not covered", "Not in the prompt and not tested."),
    (13, "Device identifiers and serial numbers", "not covered", "Not in the prompt and not tested."),
    (14, "Web addresses (URLs)", "rule", "Found by a rule (http, https and www addresses) and replaced with example.org."),
    (15, "IP addresses", "rule", "Found by a rule (four dotted numbers, each 0-255) and replaced from the documentation block 192.0.2.x."),
    (16, "Biometric identifiers, including finger and voice prints", "not covered",
     "Dictated audio is transcribed to text; voice prints are not handled."),
    (17, "Full-face photographs and comparable images", "not covered",
     "Scanned pages are read as text only; photographs are not looked for."),
    (18, "Any other unique identifying number, characteristic or code", "partial",
     "The re-identification reviewer lists clues (rare conditions, occupation, small places) for a person; they are not edited automatically. Local codes can be added with a site profile."),
]


def rows():
    return [{"number": n, "category": c, "status": s, "how": h} for n, c, s, h in CATEGORIES]


def counts():
    out = {s: 0 for s in STATUSES}
    for _, _, status, _ in CATEGORIES:
        out[status] += 1
    return out


def markdown():
    n = counts()
    lines = ["# Safe Harbor coverage", "",
             "Which of the 18 HIPAA Safe Harbor identifier categories this tool looks for, and how much is known about how well. "
             "This is an assistant for human review, not a compliance certification: a person must review the output, and "
             "Safe Harbor also requires that nobody has actual knowledge that what remains could identify the person.", "",
             "The categories follow 45 CFR 164.514(b)(2)(i) as summarized in secondary sources; check the regulation before relying on this table. "
             "Generated by `python -m deid.audit.coverage`; do not edit by hand.", "",
             "Summary: " + ", ".join(f"{n[s]} {s}" for s in STATUSES) + ".", "",
             "| # | Category | Status | What the tool does |", "|---|---|---|---|"]
    lines += [f"| {num} | {cat} | {status} | {how} |" for num, cat, status, how in CATEGORIES]
    lines += ["", "Status words: **measured** = scored on the project's synthetic sets; **rule** = found by a rule with no model, tested on invented text only; "
              "**asked** = the model is asked for it but no result is reported for this category alone; **partial** = only part of the category; "
              "**not covered** = not looked for.", ""]
    return "\n".join(lines)


def html():
    """A small table for the audit page and the app."""
    body = "".join(
        f'<tr><td>{num}</td><td>{escape(cat)}</td><td><span class="badge">{escape(status)}</span></td><td>{escape(how)}</td></tr>'
        for num, cat, status, how in CATEGORIES)
    n = counts()
    summary = ", ".join(f"{n[s]} {s}" for s in STATUSES)
    return (f'<details><summary>Safe Harbor coverage: {escape(summary)}</summary>'
            f'<p class="muted">What this tool looks for, by HIPAA Safe Harbor category. Not a compliance certification.</p>'
            f'<table><tr><th>#</th><th>Category</th><th>Status</th><th>What the tool does</th></tr>{body}</table></details>')


PATH = Path(__file__).resolve().parents[2] / "docs" / "COVERAGE.md"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if docs/COVERAGE.md differs from the generated text")
    parser.add_argument("--write", action="store_true", help="write docs/COVERAGE.md")
    args = parser.parse_args(argv)
    text = markdown()
    if args.write:
        PATH.write_text(text, encoding="utf-8", newline="\n")
        print("wrote", PATH)
    elif args.check:
        if not PATH.exists() or PATH.read_text(encoding="utf-8") != text:
            print("docs/COVERAGE.md is out of date; run python -m deid.audit.coverage --write")
            return 1
        print("docs/COVERAGE.md is up to date")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
