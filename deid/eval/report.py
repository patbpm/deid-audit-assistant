"""Build docs/RESULTS.md from the JSON files in results/ (numbers are copied, not typed).

    python -m deid.eval.report
"""

import json
from pathlib import Path

from . import TYPES

SYSTEMS = (
    ("regex", "Format-aware regex (ours)"),
    ("presidio", "Presidio, default settings"),
    ("philter", "Philter + compatibility shim"),
)

HEADER = """# Evaluation results

Generated by `python -m deid.eval.report` from `results/*.json`. Do not edit by hand.

Scope: the **test split** (patients P0051-P0150, 400 synthetic notes) of dataset seed 20261027, generator 0.1. These are baselines only; the model-based system was not run on this split (decided Oct 29, so there is no held-out model result). All numbers are on synthetic notes, so they say nothing certain about real clinical text.

Metric definitions: *recall* is the share of gold identifiers overlapped by a prediction (a miss is the failure that matters); *precision* is the share of predictions that overlap a gold identifier; *leaked chars* is the share of gold characters not covered by any prediction. Intervals are 95% bootstrap intervals over notes (1,000 resamples, seed 0).
"""

CAVEATS = """
## Read before quoting any number

- **Easy formats.** Phones, SSNs and emails use fixed fictional formats, and the regex baseline was written knowing them. Its high ID, PHONE and EMAIL recall shows how easy the synthetic data is, not how well regex works on real notes.
- **Philter ran through a shim.** Its bundled patterns use inline regex flags that Python 3.11+ rejects; `deid/baselines/philter_baseline.py` moves them to the pattern start, which keeps their old meaning. It was not run unmodified and not on the Python version it was written for. Philter cannot label identifier types, so it is scored type-agnostically.
- **Philter's spans come from a conversion.** Its output is a masked copy of the note; predictions are runs of masked characters, merged across single spaces, hyphens, slashes and periods. This choice affects its precision and leaked-character numbers. Its recall does not depend on it.
- **Presidio was not tuned.** Default `AnalyzerEngine()`, default threshold, spaCy `en_core_web_lg`. Its most frequent non-identifier predictions on the full set are the credential "MD" as a location (228), "daily" (198), "today" (100) and "this morning" (100) as dates, and the eponyms "Foley" and "Glasgow". Entity types without a project counterpart (URL, NRP, UK_NHS) are dropped.
- **Type-agnostic recall** counts a gold identifier as found when any prediction of any type overlaps it, so it is the fairest cross-system recall comparison here. Typed recall additionally requires the right label.
"""


def load(name, suffix=""):
    path = Path("results") / f"{name}-test{suffix}.json"
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def pct(value):
    return "n/a" if value is None else f"{100 * value:.1f}"


def ci(interval):
    return "" if not interval else f" ({pct(interval[0])}-{pct(interval[1])})"


def recall_table():
    rows = ["| System | " + " | ".join(TYPES) + " |", "|---|" + "---|" * len(TYPES)]
    for key, label in SYSTEMS:
        data = load(key, "-agnostic")
        if not data:
            continue
        cells = []
        for t in TYPES:
            m = data["recall_by_gold_type"][t]
            cells.append(f"{pct(m['recall'])}{ci(m['recall_ci95'])}")
        rows.append(f"| {label} | " + " | ".join(cells) + " |")
    return "\n".join(rows)


def summary_table():
    rows = [
        "| System | Recall % | Precision % | Leaked chars % | Typed recall % | Typed precision % |",
        "|---|---|---|---|---|---|",
    ]
    for key, label in SYSTEMS:
        agnostic = load(key, "-agnostic")
        typed = load(key)
        if not agnostic:
            continue
        m = agnostic["metrics"]["PHI"]
        t = typed["metrics"]["ALL"] if typed else None
        rows.append(
            f"| {label} | {pct(m['overlap']['recall'])}{ci(m['ci95']['recall'])} "
            f"| {pct(m['overlap']['precision'])}{ci(m['ci95']['precision'])} "
            f"| {pct(m['leaked_char_rate'])} "
            f"| {pct(t['overlap']['recall']) if t else 'n/a (no types)'} "
            f"| {pct(t['overlap']['precision']) if t else 'n/a (no types)'} |"
        )
    return "\n".join(rows)


def main():
    parts = [
        HEADER,
        "## Overall (type-agnostic; typed columns need the right label)\n",
        summary_table(),
        "\n## Recall by gold identifier type (type-agnostic, 95% CI)\n",
        recall_table(),
        CAVEATS,
    ]
    Path("docs/RESULTS.md").write_text("\n".join(parts), encoding="utf-8", newline="\n")
    print("wrote docs/RESULTS.md")


if __name__ == "__main__":
    main()
